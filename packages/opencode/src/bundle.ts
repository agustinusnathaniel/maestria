import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { Schema } from 'effect';
import { Agent, Skill } from '@opencode/plugin/effect';
import type { ModeKeyword } from '@maestria/shared-mode';
import { parse as parseYaml } from 'yaml';

const AgentFrontmatter = Schema.Struct({
  description: Agent.Info.fields.description,
  mode: Agent.Info.fields.mode,
  permissions: Agent.Info.fields.permissions,
});

const ModeFrontmatter = Schema.Struct({ description: Schema.String });
const SkillFrontmatter = Schema.Struct({ description: Schema.String, name: Schema.String });

export interface BundledMode {
  readonly description: string;
  /** Mode marker plus instructions, ready to prefix a prompt. */
  readonly template: string;
}

export interface BundledAgent extends Schema.Schema.Type<typeof AgentFrontmatter> {
  readonly system: string;
}

/** Package content generated by the repository sync; see sync.config.ts. */
export interface Bundle {
  readonly agents: ReadonlyMap<string, BundledAgent>;
  readonly modes: Readonly<Record<ModeKeyword, BundledMode>>;
  readonly rules: string;
  readonly skills: readonly Skill.Info[];
}

const FRONTMATTER = /^---\n(?<yaml>[\s\S]*?)\n---\n/u;
const GENERATED_NOTICE = /^\s*<!--[\s\S]*?-->/u;

// The sync notice follows frontmatter that the sync writes and precedes frontmatter it copies.
const readMarkdown = (file: string): { body: string; frontmatter: unknown } => {
  const raw = readFileSync(file, 'utf-8').replace(GENERATED_NOTICE, '').trimStart();
  const match = FRONTMATTER.exec(raw);
  const body = raw
    .slice(match?.[0].length ?? 0)
    .replace(GENERATED_NOTICE, '')
    .trim();
  return { body: `${body}\n`, frontmatter: match ? parseYaml(match.groups?.yaml ?? '') : {} };
};

/** Reads every bundled file once; a malformed bundle throws so the host reports the plugin as failed. */
export const loadBundle = (root: string): Bundle => {
  const agentsDir = path.join(root, 'agents');
  const skillsDir = path.join(root, 'skills');
  const mode = (name: ModeKeyword): BundledMode => {
    const { body, frontmatter } = readMarkdown(path.join(agentsDir, 'commands', `${name}.md`));
    return { ...Schema.decodeUnknownSync(ModeFrontmatter)(frontmatter), template: body };
  };
  return {
    agents: new Map(
      readdirSync(agentsDir)
        .filter((file) => file.endsWith('.md'))
        .map((file) => {
          const { body, frontmatter } = readMarkdown(path.join(agentsDir, file));
          const agent = {
            ...Schema.decodeUnknownSync(AgentFrontmatter)(frontmatter),
            system: body,
          };
          return [path.basename(file, '.md'), agent];
        }),
    ),
    modes: { blitz: mode('blitz'), fein: mode('fein'), sonar: mode('sonar') },
    rules: readMarkdown(path.join(root, 'rules', 'AGENTS.md')).body,
    skills: readdirSync(skillsDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map(({ name: id }) => {
        const file = path.join(skillsDir, id, 'SKILL.md');
        const { body, frontmatter } = readMarkdown(file);
        const { description, name } = Schema.decodeUnknownSync(SkillFrontmatter)(frontmatter);
        return Schema.decodeSync(Skill.Info)({ content: body, description, id, name, path: file });
      }),
  };
};
