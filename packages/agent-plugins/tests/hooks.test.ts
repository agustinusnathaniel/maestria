import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vite-plus/test';

const root = path.resolve(import.meta.dirname, '..');
const hooks = path.join(root, 'hooks');
let repo = '';

beforeAll(() => {
  repo = fs.mkdtempSync(path.join(os.tmpdir(), 'maestria-hooks-'));
  execFileSync('git', ['init', '-q', '-b', 'main', repo]);
  fs.writeFileSync(path.join(repo, 'generated.ts'), '// @generated by a tool\nexport {};\n');
  fs.writeFileSync(path.join(repo, 'source.ts'), 'export {};\n');
});

afterAll(() => {
  fs.rmSync(repo, { force: true, recursive: true });
});

interface Run {
  readonly output: unknown;
  readonly status: number | null;
}

const run = (script: string, args: string[], input: object, env: object = {}): Run => {
  const result = spawnSync('node', [path.join(hooks, script), ...args], {
    encoding: 'utf-8',
    env: { ...process.env, CLAUDE_PROJECT_DIR: '', CURSOR_PROJECT_DIR: '', ...env },
    input: JSON.stringify(input),
  });
  const text = result.stdout.trim();
  return { output: text === '' ? undefined : (JSON.parse(text) as unknown), status: result.status };
};

const edit = (file: string): object => ({
  cwd: repo,
  tool_input: { file_path: file },
  tool_name: 'Edit',
});

const codexPatch = (agentType?: string): object => ({
  ...(agentType === undefined ? {} : { agent_id: 'a1', agent_type: agentType }),
  cwd: repo,
  tool_input: { command: '*** Begin Patch\n*** Update File: source.ts\n' },
  tool_name: 'apply_patch',
});

const cursorShell = (command: string): unknown =>
  run('git-safety.mjs', ['cursor'], { command, cwd: repo }).output;

const registeredCommands = (value: unknown): string[] =>
  typeof value === 'object' && value !== null
    ? Object.entries(value).flatMap(([key, item]) =>
        key === 'command' && typeof item === 'string' ? [item] : registeredCommands(item),
      )
    : [];

const readJson = (file: string): unknown =>
  JSON.parse(fs.readFileSync(path.join(root, file), 'utf-8'));

const HOOK_COMMAND = /hooks\/(?<script>[a-z-]+\.mjs)"? (?<host>\S+)/u;

const shell = (command: string): object => ({
  cwd: repo,
  tool_input: { command },
  tool_name: 'Bash',
});

describe('PreToolUse adapters', () => {
  it('asks natively on Claude Code and ZCode, and stays silent when allowed', () => {
    const asked = run('git-safety.mjs', ['claude'], shell('git push --force'));
    expect(asked).toMatchObject({
      output: { hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'ask' } },
      status: 0,
    });
    expect(JSON.stringify(asked.output)).toContain('force push');
    expect(run('git-safety.mjs', ['claude'], shell('git status'))).toEqual({
      output: undefined,
      status: 0,
    });
  });

  it('reads the session branch: committing on main asks', () => {
    const { output } = run('git-safety.mjs', ['claude'], shell('git commit -m x'));
    expect(JSON.stringify(output)).toContain('protected branch main');
  });

  it('turns ask into a block that names the needed approval where the host cannot ask', () => {
    for (const host of ['codex', 'kimi']) {
      const { output } = run('git-safety.mjs', [host], shell('git reset --hard'));
      expect(output).toMatchObject({ hookSpecificOutput: { permissionDecision: 'deny' } });
      expect(JSON.stringify(output)).toContain("needs the user's explicit approval");
    }
    const devin = run('git-safety.mjs', ['devin'], shell('git reset --hard')).output;
    expect(devin).toMatchObject({ decision: 'block' });
    expect(JSON.stringify(devin)).toContain("needs the user's explicit approval");
  });

  it('always answers Cursor shell hooks with JSON, using its ask', () => {
    expect(cursorShell('git status')).toEqual({ permission: 'allow' });
    expect(cursorShell('git push --force')).toMatchObject({ permission: 'ask' });
    expect(cursorShell('git commit --no-verify -m x')).toMatchObject({ permission: 'deny' });
  });

  it('scans outgoing PR text for email addresses', () => {
    const { output } = run(
      'email-scan.mjs',
      ['claude'],
      shell('gh pr create --title x --body "thanks a.person@example.org"'),
    );
    expect(output).toMatchObject({ hookSpecificOutput: { permissionDecision: 'ask' } });
    expect(JSON.stringify(output)).not.toContain('a.person@example.org');
  });

  it('guards edits to generated files: ask on Claude Code, block on Cursor', () => {
    expect(run('generated-guard.mjs', ['claude'], edit('generated.ts')).output).toMatchObject({
      hookSpecificOutput: { permissionDecision: 'ask' },
    });
    expect(run('generated-guard.mjs', ['claude'], edit('source.ts')).output).toBeUndefined();
    expect(run('generated-guard.mjs', ['cursor'], edit('generated.ts')).output).toMatchObject({
      permission: 'deny',
    });
  });

  it('blocks edits inside the Codex reviewer subagent only', () => {
    const reviewer = run('reviewer-guard.mjs', ['codex'], codexPatch('maestria-reviewer')).output;
    expect(reviewer).toMatchObject({ hookSpecificOutput: { permissionDecision: 'deny' } });
    expect(JSON.stringify(reviewer)).toContain('reviewer is read-only');
    expect(run('reviewer-guard.mjs', ['codex'], codexPatch()).output).toBeUndefined();
    expect(run('reviewer-guard.mjs', ['codex'], codexPatch('worker')).output).toBeUndefined();
  });

  it('fails open on unreadable input and unknown hosts', () => {
    const garbage = spawnSync('node', [path.join(hooks, 'git-safety.mjs'), 'claude'], {
      encoding: 'utf-8',
      input: 'not json',
    });
    expect(garbage.status).toBe(0);
    expect(garbage.stdout).toBe('');
    expect(run('git-safety.mjs', ['nope'], shell('git push --force')).output).toBeUndefined();
  });
});

describe('SessionStart adapters', () => {
  it('prints each always-on core part as Claude Code and ZCode context, under the 10,000 cap', () => {
    for (const [part, heading] of [
      ['core-loop', '## Routing'],
      ['core-rules', '## Universal Floors'],
    ]) {
      const { output } = run('core-context.mjs', ['claude', part], { source: 'compact' });
      expect(output).toMatchObject({ hookSpecificOutput: { hookEventName: 'SessionStart' } });
      const context = JSON.stringify(output);
      expect(context).toContain(heading);
      expect(
        fs.readFileSync(path.join(hooks, 'context', `${part}.md`), 'utf-8').length,
      ).toBeLessThanOrEqual(10_000);
    }
  });

  it('injects project customization in order, and nothing when it is absent', () => {
    expect(run('project-context.mjs', ['claude'], { cwd: repo }).output).toBeUndefined();
    fs.mkdirSync(path.join(repo, '.maestria'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.maestria', 'rules.md'), 'Rule B\n');
    fs.writeFileSync(path.join(repo, '.maestria', 'workflow.md'), 'Workflow A\n');
    const { output } = run('project-context.mjs', ['devin'], { cwd: repo });
    const context = JSON.stringify(output);
    expect(context.indexOf('Workflow A')).toBeLessThan(context.indexOf('Rule B'));
    const cursor = run('project-context.mjs', ['cursor'], { workspace_roots: [repo] }).output;
    expect(Object.keys(cursor ?? {})).toEqual(['additional_context']);
    expect(JSON.stringify(cursor)).toContain('Workflow A');
    fs.writeFileSync(path.join(repo, '.maestria', 'rules.md'), 'x'.repeat(12_000));
    expect(JSON.stringify(run('project-context.mjs', ['claude'], { cwd: repo }).output)).toContain(
      'too long to supply here',
    );
    fs.rmSync(path.join(repo, '.maestria'), { force: true, recursive: true });
  });
});

describe('hook registrations', () => {
  it.each([
    ['hooks/hooks.json', 'claude'],
    ['hooks/codex.json', 'codex'],
    ['hooks/cursor.json', 'cursor'],
    ['hooks.json', 'devin'],
    ['kimi.plugin.json', 'kimi'],
  ])('%s runs existing job scripts for %s', (file, host) => {
    const registered = registeredCommands(readJson(file));
    expect(registered.length).toBeGreaterThan(0);
    for (const command of registered) {
      const { host: hostArgument = '', script = '' } = HOOK_COMMAND.exec(command)?.groups ?? {};
      expect(fs.existsSync(path.join(hooks, script)), command).toBe(true);
      expect(hostArgument).toBe(host);
    }
  });

  it('selects host hook files explicitly where a default file would load the wrong format', () => {
    expect(readJson('.codex-plugin/plugin.json')).toMatchObject({ hooks: './hooks/codex.json' });
    expect(readJson('.cursor-plugin/plugin.json')).toMatchObject({ hooks: './hooks/cursor.json' });
  });

  it('loads the core on Claude Code and ZCode at startup, resume, clear, and compaction', () => {
    expect(JSON.stringify(readJson('hooks/hooks.json'))).toContain('startup|resume|clear|compact');
  });
});
